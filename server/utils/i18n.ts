// Fase 7 — tradução de mensagens do servidor (erros devolvidos por
// `createError({ message })`, que chegam ao client via `e?.data?.message` e
// muitas vezes vão direto para um toast). O servidor não tem acesso ao
// vue-i18n; isto é um dicionário mínimo, só com as chaves realmente usadas
// (nunca um mapeamento genérico de todas as strings da app).
//
// Locale lido do cookie `financeflow_locale` (mesmo que o client usa, ver
// nuxt.config.ts → i18n e plugins/locale.ts) — cada endpoint chama
// `getServerLocale(event)` e depois `serverT(locale, 'chave', params)`.
import type { H3Event } from 'h3'

export type ServerLocale = 'pt-PT' | 'en' | 'fr' | 'de' | 'it' | 'es'
const SUPPORTED_LOCALES: ServerLocale[] = ['pt-PT', 'en', 'fr', 'de', 'it', 'es']

export function getServerLocale(event: H3Event): ServerLocale {
  const cookie = getCookie(event, 'financeflow_locale')
  return (SUPPORTED_LOCALES as string[]).includes(cookie || '') ? (cookie as ServerLocale) : 'en'
}

